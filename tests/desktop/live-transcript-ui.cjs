    transcript.speech_model={state:'ready',name:'small.en'};
    transcript.preview=Array(100).fill('More live speech.').join('\n');
    socket.send(JSON.stringify({schema_version:1,kind:'heartbeat',cursor:0}));
    await preview.getByText(/Transcribing now/).waitFor();
